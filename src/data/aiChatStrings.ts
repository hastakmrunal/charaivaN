export function getAiChatStrings(language: Pick<Language, 'code' | 'nativeName'>): AiChatUiStrings {
  const code = language?.code || 'en';
  const merged: AiChatUiStrings = {
    ...EN_STRINGS,
    ...(TRANSLATIONS[code] || {}),
  };
  return {
    ...merged,
    askPlaceholder: merged.askPlaceholder.replace('{language}', language?.nativeName || 'English'),
  };
}
